const ALL_EMOJIS = EMOJI_CATEGORIES.flatMap((c) => c.emojis);

export function loadRecentEmojis() {
  try {
    const list = JSON.parse(localStorage.getItem(RECENT_KEY) || '[]');
    return Array.isArray(list) ? list.filter((e) => ALL_EMOJIS.includes(e)).slice(0, 24) : [];
  } catch {
    return [];
  }
}

export function saveRecentEmoji(emoji) {
  const recent = [emoji, ...loadRecentEmojis().filter((e) => e !== emoji)].slice(0, 24);
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify(recent));
  } catch {}
}

function buildGrid(emojis, onPick) {
  if (!emojis.length) {
    return `<div class="ep-empty">Ничего не найдено</div>`;
  }
  return `<div class="ep-grid">${emojis
    .map((e) => `<button type="button" class="ep-item" data-emoji="${e}" title="${e}">${e}</button>`)
    .join('')}</div>`;
}

/**
 * @param {HTMLElement} container
 * @param {{ onPick: (emoji: string) => void }} opts
 */
export function renderEmojiPicker(container, { onPick }) {
  const recent = loadRecentEmojis();
  container.innerHTML = `
    <div class="ep-search-row">
      <input class="ep-search" type="text" placeholder="Поиск эмодзи…" autocomplete="off" />
      <button type="button" class="ep-clear hidden" aria-label="Очистить">×</button>
    </div>
    <div class="ep-tabs">${EMOJI_CATEGORIES.map(
      (c, i) =>
        `<button type="button" class="ep-tab ${i === 0 ? 'active' : ''}" data-cat="${c.id}" title="${c.label}">${c.icon}</button>`
    ).join('')}</div>
    <div class="ep-scroll">${recent.length ? `<div class="ep-recent-label">Недавние</div>${buildGrid(recent, onPick)}` : ''}${buildGrid(
      EMOJI_CATEGORIES[0].emojis,
      onPick
    )}</div>`;

  const search = container.querySelector('.ep-search');
  const clear = container.querySelector('.ep-clear');
  const tabs = container.querySelectorAll('.ep-tab');
  const scroll = container.querySelector('.ep-scroll');

  function showCategory(catId) {
    const cat = EMOJI_CATEGORIES.find((c) => c.id === catId);
    if (!cat) return;
    scroll.innerHTML = `${buildGrid(cat.emojis, onPick)}`;
    tabs.forEach((t) => t.classList.toggle('active', t.dataset.cat === catId));
  }

  function showSearch(query) {
    const q = query.trim().toLowerCase();
    clear.classList.toggle('hidden', !q);
    tabs.forEach((t) => t.classList.remove('active'));
    if (!q) {
      scroll.innerHTML = `${recent.length ? `<div class="ep-recent-label">Недавние</div>${buildGrid(recent, onPick)}` : ''}${buildGrid(
        EMOJI_CATEGORIES[0].emojis,
        onPick
      )}`;
      tabs[0]?.classList.add('active');
      return;
    }
    const matches = ALL_EMOJIS.filter((e) => e.includes(q) || (EMOJI_KEYWORDS[e] || '').toLowerCase().includes(q)).slice(0, 120);
    scroll.innerHTML = buildGrid(matches, onPick);
  }

  search.addEventListener('input', () => showSearch(search.value));
  clear.addEventListener('click', () => {
    search.value = '';
    showSearch('');
    search.focus();
  });

  container.addEventListener('click', (e) => {
    const tab = e.target.closest('.ep-tab');
    if (tab) {
      search.value = '';
      clear.classList.add('hidden');
      showCategory(tab.dataset.cat);
      return;
    }
    const item = e.target.closest('.ep-item');
    if (item) {
      saveRecentEmoji(item.dataset.emoji);
      onPick(item.dataset.emoji);
    }
  });
}
